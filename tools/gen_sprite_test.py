"""Write assets/sprite_test.png + assets/sprite_test.sheet: a pixel-art test unit.

64x64 frames, 48 px per metre, feet at (32, 62). Rows: clip x facing
(front, right, back, left), columns: frames. Front shows a face, back a cape,
right/left a profile with a nose and a sword on the facing side, so the row
in use is obvious on screen. Frame number = dots above the head.
Clips Idle/Walk/Attack/Hurt/Death; Attack hit event at 0.35 s (frame 2 of 4 at 8 fps).

Run: python3 tools/gen_sprite_test.py [out_dir]
"""
import os
import sys

from PIL import Image, ImageDraw

FW, FH = 64, 64
PPU = 48
ANCHOR = (32, 62)
CLIPS = [("Idle", 2, 4), ("Walk", 4, 8), ("Attack", 4, 8), ("Hurt", 2, 8), ("Death", 3, 6)]
EVENTS = [("Attack", 1, 0.35)]
OUTLINE = (24, 18, 30, 255)
SKIN = (240, 196, 150, 255)
TUNIC = [(200, 60, 60, 255), (60, 160, 80, 255), (60, 90, 200, 255), (220, 180, 50, 255)]
HAIR = (90, 55, 30, 255)
STEEL = (200, 210, 220, 255)
BOOT = (70, 50, 40, 255)
FLASH = (255, 255, 255, 255)


def rect(d, x0, y0, x1, y1, c):
    d.rectangle([x0, y0, x1, y1], fill=c, outline=OUTLINE)


def figure(d, facing, clip, f, frames):
    bob = 1 if clip == "Idle" and f == 1 else 0
    lean = 0
    if clip == "Hurt":
        lean = -2 if facing != 3 else 2
    tunic = FLASH if clip == "Hurt" and f == 0 else TUNIC[facing]
    if clip == "Death":
        y = 46 + f * 4
        rect(d, 14, y, 50, y + 10, tunic)
        rect(d, 50, y + 1, 58, y + 9, SKIN)
        return
    side = 1 if facing == 1 else -1 if facing == 3 else 0
    step = [0, 3, 0, -3][f % 4] if clip == "Walk" else 0
    cx = 32 + lean
    top = 14 + bob
    rect(d, cx - 4 - step, 50, cx - 1 - step, 61, BOOT)
    rect(d, cx + 1 + step, 50, cx + 4 + step, 61, BOOT)
    rect(d, cx - 8, top + 16, cx + 8, 51, tunic)
    if facing == 2:
        rect(d, cx - 9, top + 15, cx + 9, 48, (120, 30, 40, 255))
    rect(d, cx - 7, top, cx + 7, top + 14, SKIN)
    if facing == 0:
        d.rectangle([cx - 7, top, cx + 7, top + 3], fill=HAIR)
        d.point([(cx - 3, top + 7), (cx + 3, top + 7)], fill=OUTLINE)
        d.line([(cx - 2, top + 11), (cx + 2, top + 11)], fill=OUTLINE)
    elif facing == 2:
        d.rectangle([cx - 6, top + 1, cx + 6, top + 13], fill=HAIR)
    else:
        d.rectangle([cx - 7, top, cx + 7, top + 3], fill=HAIR)
        hx = cx + 7 * side
        d.rectangle([min(hx, hx + side * 2), top + 7, max(hx, hx + side * 2), top + 9], fill=SKIN)
        d.point([(cx + 3 * side, top + 6)], fill=OUTLINE)
    if side:
        reach = {"Attack": [2, 6, 12, 4]}.get(clip, [0] * 4)[f % 4]
        hand_x = cx + side * (9 + reach)
        hand_y = top + 24 - (6 if clip == "Attack" and f == 1 else 0)
        rect(d, min(cx + side * 8, hand_x), hand_y, max(cx + side * 8, hand_x), hand_y + 3, SKIN)
        tip = hand_x + side * 10
        d.line([(hand_x, hand_y + 1), (tip, hand_y + 1 - (8 if clip == "Attack" and f == 1 else 0))],
               fill=STEEL, width=2)
    for i in range(f + 1):
        d.rectangle([4 + i * 4, 2, 5 + i * 4, 3], fill=OUTLINE)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "assets")
    cols = max(n for _, n, _ in CLIPS)
    rows = len(CLIPS) * 4
    img = Image.new("RGBA", (cols * FW, rows * FH), (0, 0, 0, 0))
    for ci, (name, frames, _) in enumerate(CLIPS):
        for facing in range(4):
            for f in range(frames):
                tile = Image.new("RGBA", (FW, FH), (0, 0, 0, 0))
                figure(ImageDraw.Draw(tile), facing, name, f, frames)
                img.paste(tile, (f * FW, (ci * 4 + facing) * FH))
    img.save(os.path.join(out, "sprite_test.png"))
    lines = ["# generated by tools/gen_sprite_test.py", f"frame {FW} {FH}", f"ppu {PPU}",
             f"anchor {ANCHOR[0]} {ANCHOR[1]}", "dirs 4"]
    lines += [f"clip {n} {k} {fps}" for n, k, fps in CLIPS]
    lines += [f"event {n} {i} {t}" for n, i, t in EVENTS]
    with open(os.path.join(out, "sprite_test.sheet"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
